export function translateLeaseChinese(raw: string): string {
  if (raw === '要') return '需确认（房源标注「要」）';
  const normalized = raw.normalize('NFKC');
  let value = normalized
    .replace(/(\d+)\s*年(?:毎|ごと)に?/g, '每 $1 年 ')
    .replace(/(\d+)\s*ヶ月ごと/g, '每 $1 个月')
    .replace(/(\d[\d,.]*)\s*[ヶケかカ箇]月(?:分)?/g, '$1 个月')
    .replace(/(\d)\s*(万)?円/g, '$1 $2日元')
    .replace(/(\d)\s*(年|月上旬|月中旬|月下旬)/g, '$1 $2');
  for (const [source, translation] of terms) value = value.replaceAll(source, translation);
  if (raw === '即') return '可立即入住';
  if (raw === '-') return '—';
  value = value.replaceAll('総', '总');
  return value === normalized ? raw : value.replace(/(租金(?:总额|等费用)?)の/g, '$1的');
}
